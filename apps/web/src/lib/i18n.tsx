type LocaleContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: keyof typeof en, vars?: Record<string, string | number>) => string
}

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}

// A no-provider fallback keeps non-app consumers (unit tests, isolated previews)
// from throwing; the app always mounts <LocaleProvider> in main.tsx.
const fallbackLocale: LocaleContextValue = {
  locale: "en",
  setLocale: () => {},
  t: (key, vars) => interpolate(en[key], vars),
}
const LocaleContext = createContext<LocaleContextValue>(fallbackLocale)

export function LocaleProvider({ children, initial = "en" }: { children: ReactNode; initial?: Locale }) {
  const [locale, setLocale] = useState<Locale>(initial)
  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (key, vars) => interpolate(locale === "zh" ? zh[key] : en[key], vars),
  }), [locale])
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  return useContext(LocaleContext)
}
